/**
 * セール前の8週間を週ごとに並べた例（n＝くらべる値段で売った週・o＝ほかの値段で売った週・''＝まだ売っていない週。最後の週がセールの前の週）
 * 考え方の文の3つの条件を週の数で見る。売っていた期間が8週間より短いときは、その期間で見る
 */
export function kangae(weeks) {
  const sold = weeks.filter((w) => w !== '').length;
  const n = weeks.filter((w) => w === 'n').length;
  const last = weeks.lastIndexOf('n');
  const gap = last < 0 ? weeks.length : weeks.length - 1 - last; // 最後にその値段で売った週のあとの週の数
  const kahan = n * 2 > sold;
  const two = n >= 2;
  const recent = gap < 2;
  return { sold, n, gap, kahan, two, recent, ok: kahan && two && recent };
}


// 8週の帯：同じ値段の週をまとめて1つの区切りにする
function weekBand(r) {
  const parts = [];
  for (const w of r.weeks) {
    const last = parts[parts.length - 1];
    if (last && last.k === w) last.c += 1;
    else parts.push({ k: w, c: 1 });
  }
  const word = { n: 'その値段', o: 'ほか', '': 'なし' };
  return band({
    head: r.name,
    parts: parts.map((x) => ({ w: x.c * 12.5, kind: x.k === 'n' ? 'pay' : 'alt', text: x.c >= 2 ? `${word[x.k]} ${x.c}週` : `${x.c}週` })),
    ruler: [[0, '8週間前'], [50, '半分'], [100, 'セールの前の日']],
    ans: `考え方では<b>${r.ok ? '当たる' : '当たらない'}</b>`,
    label: `${r.name}の8週間の帯。その値段で売ったのは${r.n}週`,
  });
}

